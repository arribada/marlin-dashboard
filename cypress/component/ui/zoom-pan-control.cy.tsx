import ZoomPanControls from "@/_components/ui/zoom-pan-control";
import { TIMELINE_CONFIG } from "@/_lib/constants";
import { useState } from 'react';

describe('ZoomPanControls', () => {
  const Wrapper = () => {
    const [zoomLevel, setZoomLevel] = useState(1);
    const [panOffset, setPanOffset] = useState(0);

    return (
      <ZoomPanControls
        zoomLevel={zoomLevel}
        setZoomLevel={setZoomLevel}
        panOffset={panOffset}
        setPanOffset={setPanOffset}
      />
    );
  };

  beforeEach(() => {
    cy.mount(<Wrapper />);
  });

  it('renders zoom and pan controls', () => {
    cy.getByTestId("zoom-control").should('exist');
    cy.contains('Zoom:').should('exist');
    cy.contains('Full Trip').should('exist');
  });

  it('zooms in when ZoomIn button is clicked', () => {
    cy.getByTestId("zoom-in").click();
    cy.contains('Pan').should('exist'); // now zoomLevel > 1
  });

  it('zooms out when ZoomOut button is clicked', () => {
    cy.getByTestId("zoom-in").click();
    cy.getByTestId("zoom-out").click();
    cy.contains('Full Trip').should('exist'); // zoomLevel back to 1
  });

  it('disables ZoomOut button at minimum zoom', () => {
    cy.getByTestId("zoom-out").should('be.disabled');
  });

  it('disables ZoomIn button at max zoom', () => {
    // Zoom levels generated by repeatedly clicking `ZoomIn` starting from 1.
    // Each click doubles the zoom, capped at 100, (as defined in the component logic).
    const zoomLevels: number[] = [];
    for (let z = TIMELINE_CONFIG.MIN_ZOOM_LEVEL; z < TIMELINE_CONFIG.MAX_ZOOM_LEVEL; z *= 2) {
      zoomLevels.push(z);
    }
    zoomLevels.push(TIMELINE_CONFIG.MAX_ZOOM_LEVEL);

    zoomLevels.forEach((_, index) => {
      cy.getByTestId("zoom-in").then($btn => {
        const disabled = $btn.prop('disabled');
        if (index === zoomLevels.length - 1) {
          // Last zoom level should disable the button
          expect(disabled).to.be.true;
        } else {
          expect(disabled).to.be.false;
        }
      });

      if (index < zoomLevels.length - 1) {
        cy.getByTestId("zoom-in").click();
      }
    });
  });

  it('pans left and right correctly', () => {
    cy.getByTestId("zoom-in").click(); // zoomLevel > 1

    cy.getByTestId("pan-right").click();
    cy.contains('Pan').should('exist');

    cy.getByTestId("pan-left").click();
    cy.contains('Pan').should('exist');
  });

  it('disables pan buttons at boundaries', () => {
    cy.getByTestId("zoom-in").click(); // zoomLevel > 1

    cy.getByTestId("pan-left").should('be.disabled'); // panOffset at 0

    // move panOffset to 100
    for (let i = 0; i < 10; i++) {
      cy.getByTestId("pan-right").click();
    }
    cy.getByTestId("pan-right").should('be.disabled');
  });
});
